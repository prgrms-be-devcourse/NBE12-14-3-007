-- 관리자가 직접 바꾼 등급은 자정 집계가 건드리지 않도록 표시한다. (영구 고정, 해제는 DB에서 직접)
ALTER TABLE member
    ADD COLUMN role_locked BOOLEAN NOT NULL DEFAULT FALSE;

-- 관리자의 등급 변경 이력. 누가, 언제, 어떤 등급에서 어떤 등급으로, 왜 바꿨는지 남긴다.
CREATE TABLE member_role_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  UUID         NOT NULL REFERENCES member (id),
    actor_id   UUID         NOT NULL REFERENCES member (id),
    old_role   VARCHAR(32)  NOT NULL,
    new_role   VARCHAR(32)  NOT NULL,
    -- 제재(ROLE_WARNING)로 바꿀 때만 필수라서 비어 있을 수 있다.
    reason     VARCHAR(500),
    created_at TIMESTAMP    NOT NULL
);

CREATE INDEX idx_member_role_history_member ON member_role_history (member_id, created_at DESC);
